// Мат: корни с границами слова, чтобы не ловить «корабля», «небо», «художник».
const MAT_RE = new RegExp(
  [
    'ху[йяеёию]',
    'пизд',
    '(^|[^а-яё])бля',
    '(^|[^а-яё])(за|на|по|у|вы|от|до|раз|рас|при|об|съ|въ|подъ|изъ|отъ|о)?[её]б(а|у|л|н|ись|ёт|ет|и|ыв)',
    '(^|[^а-яё])сук(а|и|ой|у)(?![а-яё])',
    'мудак', 'мудил', 'залуп', 'гандон', 'долбо[её]б',
    '(^|[^а-яё])нах(уй|ер)',
  ].join('|'),
  'i',
);

// Оскорбления по нации, ориентации, здоровью: вырезаем всегда.
const SLUR_RE = /(^|[^а-яё])(пид[ао]р|педик|жид(?!к)|хач(?!ап)|чурк|ниггер|негр|даун|хох[оа]?л|кацап|москал)/i;

export const hasMat = (s) => MAT_RE.test(s);
export const hasSlur = (s) => SLUR_RE.test(s);
